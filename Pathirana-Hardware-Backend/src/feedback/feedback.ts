/**
 * Customer feedback (migration 0007): submitted on the website, published only
 * after a staff member approves it. No contact details, IP addresses or
 * accounts are collected. The public API returns approved feedback only and
 * never any moderation data.
 */

export const FEEDBACK_STATUSES = ["pending", "approved", "rejected", "hidden"] as const;
export type FeedbackStatus = (typeof FEEDBACK_STATUSES)[number];
export const FEEDBACK_LANGUAGES = ["en", "ta", "si"] as const;
export const FEEDBACK_LIMITS = { name: [2, 60], message: [10, 1000], location: [2, 80] } as const;
/** Version of the consent wording shown on the website form (recorded with each submission). */
/** Accepted consent wordings: "-v2" = review + publish-if-approved with the display name (current). */
export const CONSENT_VERSIONS = ["2026-11-20", "2026-11-20-v2"] as const;
const DUPLICATE_WINDOW_HOURS = 24;

/** Moderation actions → allowed current statuses and the resulting status. */
const TRANSITIONS = {
  approve: { from: ["pending"], to: "approved" },
  reject: { from: ["pending"], to: "rejected" },
  hide: { from: ["approved"], to: "hidden" },
  restore: { from: ["hidden"], to: "approved" },
} as const satisfies Record<string, { from: readonly FeedbackStatus[]; to: FeedbackStatus }>;
type Action = keyof typeof TRANSITIONS;

export class FeedbackInput {
  /** Generated by the browser once per form: a retried submission returns the same record. */
  @IsUUID() idempotencyKey!: string;
  @IsString() @MinLength(1) @MaxLength(200) name!: string;
  @Type(() => Number) @IsInt() @Min(1) @Max(5) rating!: number;
  @IsString() @MinLength(1) @MaxLength(4000) message!: string;
  @IsOptional() @IsString() @MaxLength(200) location?: string;
  @IsIn(FEEDBACK_LANGUAGES) language!: (typeof FEEDBACK_LANGUAGES)[number];
  @IsBoolean() @Equals(true, { message: "consent is required" }) consent!: boolean;
  @IsIn(CONSENT_VERSIONS) consentVersion!: string;
  /** Anti-spam honeypot: hidden in the form, so a person leaves it empty. Never stored. */
  @IsOptional() @IsString() @MaxLength(200) website?: string;
}

class PublicFeedbackQuery {
  @IsOptional() @Type(() => Number) @IsInt() @Min(1) @Max(24) limit: number = 12;
}

class AdminFeedbackQuery {
  @IsOptional() @IsIn(FEEDBACK_STATUSES) status?: FeedbackStatus;
  @IsOptional() @Type(() => Number) @IsInt() @Min(1) @Max(10_000) page: number = 1;
  @IsOptional() @Type(() => Number) @IsInt() @Min(1) @Max(100) limit: number = 20;
}

class ModerationBody {
  /** Optional internal note (never shown publicly). */
  @IsOptional() @IsString() @MaxLength(500) note?: string;
}

/** Format/control characters become spaces, EXCEPT the zero-width (non-)joiners that Sinhala and Tamil
 *  spelling needs (U+200C / U+200D) and, in multi-line text, the newline. */
const keepJoiners =
  (replacement: string, ...keep: string[]) =>
  (c: string) =>
    c.codePointAt(0) === 0x200c || c.codePointAt(0) === 0x200d || keep.includes(c) ? c : replacement;
const FORMAT_CHARS = /[\p{Cc}\p{Cf}\p{Zl}\p{Zp}]/gu;
/** Single-line text: Unicode NFC, control characters removed, spaces collapsed. */
const cleanLine = (v: string | undefined | null) => {
  const t = v?.normalize("NFC").replace(FORMAT_CHARS, keepJoiners(" ")).replace(/\s+/g, " ").trim();
  return t ? t : null;
};
/** Multi-line text: keeps single blank lines, removes control characters. */
const cleanText = (v: string) =>
  v
    .normalize("NFC")
    .replace(/\r\n?/g, "\n")
    .replace(FORMAT_CHARS, keepJoiners(" ", "\n"))
    .split("\n")
    .map((l) => l.replace(/[ \t]+/g, " ").trim())
    .join("\n")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
/** Length in user-perceived characters (a Tamil / Sinhala letter with signs counts once). */
const graphemes = (s: string) => {
  const seg = new Intl.Segmenter(undefined, { granularity: "grapheme" });
  let n = 0;
  for (const _ of seg.segment(s)) n++;
  return n;
};
/** Web links and bare domains: reviews never need them, spam almost always has them. */
const hasLink = (s: string | null) =>
  Boolean(s) &&
  /(https?:\/\/|www\.|\b[a-z0-9-]+\.(com|net|org|lk|xyz|info|biz|ru|io|co|top|site)\b)/i.test(s!);

const PUBLIC_COLUMNS = `id, display_name AS "name", rating, message, location, language,
  to_char(approved_at AT TIME ZONE 'Asia/Colombo', 'YYYY-MM') AS "month"`;
const ADMIN_COLUMNS = `f.id, f.display_name AS "name", f.rating, f.message, f.location, f.language, f.status,
  f.publish_consent AS "consent", f.consent_version AS "consentVersion", f.moderation_note AS "note",
  f.submitted_at AS "submittedAt", f.moderated_at AS "moderatedAt", s.full_name AS "moderatedBy",
  f.approved_at AS "approvedAt"`;

@Injectable()
export class FeedbackService {
  constructor(
    private readonly db: DatabaseService,
    private readonly audit: AuditService,
  ) {}

  async submit(input: FeedbackInput) {
    // Filled honeypot → automated submission: refused, nothing is saved.
    if (input.website?.trim()) throw new BadRequestException(["This feedback could not be accepted."]);
    const name = cleanLine(input.name);
    const message = cleanText(input.message);
    const location = cleanLine(input.location);
    const problems: string[] = [];
    const [nMin, nMax] = FEEDBACK_LIMITS.name;
    const [mMin, mMax] = FEEDBACK_LIMITS.message;
    const [lMin, lMax] = FEEDBACK_LIMITS.location;
    if (!name || graphemes(name) < nMin || name.length > nMax)
      problems.push(`name must be ${nMin}–${nMax} characters`);
    if (graphemes(message) < mMin || message.length > mMax)
      problems.push(`message must be ${mMin}–${mMax} characters`);
    if (location && (graphemes(location) < lMin || location.length > lMax))
      problems.push(`location must be ${lMin}–${lMax} characters`);
    if (hasLink(message) || hasLink(name) || hasLink(location))
      problems.push("links are not allowed in feedback");
    if (problems.length) throw new BadRequestException(problems);

    const hash = createHash("sha256")
      .update(JSON.stringify([name!.toLowerCase(), message.toLowerCase().replace(/\s+/g, " ")]))
      .digest("hex");

    // Duplicate protection: the same form (retry / double tap), or the same name + message within a day.
    const existing = await this.db.one<{ content_hash: string }>(
      `SELECT content_hash FROM customer_feedback
        WHERE idempotency_key = $1 OR (content_hash = $2 AND submitted_at > now() - make_interval(hours => $3))
        ORDER BY (idempotency_key = $1) DESC LIMIT 1`,
      [input.idempotencyKey, hash, DUPLICATE_WINDOW_HOURS],
    );
    if (existing) {
      if (existing.content_hash !== hash) {
        throw new ConflictException(
          "This form was already submitted with different details. Reload the page to send new feedback.",
        );
      }
      return { status: "pending" as const, duplicate: true };
    }
    try {
      await this.db.query(
        `INSERT INTO customer_feedback (idempotency_key, content_hash, display_name, rating, message, location,
                                        language, publish_consent, consent_version)
         VALUES ($1, $2, $3, $4, $5, $6, $7, true, $8)`,
        [
          input.idempotencyKey,
          hash,
          name,
          input.rating,
          message,
          location,
          input.language,
          input.consentVersion,
        ],
      );
    } catch (e) {
      const err = e as { code?: string; constraint?: string };
      if (err.code === "23505" && err.constraint === "customer_feedback_idempotency_key") {
        return { status: "pending" as const, duplicate: true };
      }
      throw e;
    }
    return { status: "pending" as const, duplicate: false };
  }

  /** Approved feedback only, newest first. No ids of staff, notes, dates of moderation or status. */
  async listPublic(limit: number) {
    const items = await this.db.query<{ id: string }>(
      `SELECT ${PUBLIC_COLUMNS} FROM customer_feedback WHERE status = 'approved'
        ORDER BY approved_at DESC, id LIMIT $1`,
      [limit],
    );
    return { items };
  }

  async list(q: AdminFeedbackQuery) {
    const params: unknown[] = [];
    let where = "";
    if (q.status) {
      params.push(q.status);
      where = "WHERE f.status = $1";
    }
    const rows = await this.db.query<{ total: number }>(
      `SELECT ${ADMIN_COLUMNS}, count(*) OVER ()::int AS total
         FROM customer_feedback f LEFT JOIN staff s ON s.id = f.moderated_by ${where}
        ORDER BY (f.status = 'pending') DESC, f.submitted_at DESC
        LIMIT $${params.length + 1} OFFSET $${params.length + 2}`,
      [...params, q.limit, (q.page - 1) * q.limit],
    );
    const counts = await this.db.query<{ status: FeedbackStatus; n: number }>(
      "SELECT status, count(*)::int AS n FROM customer_feedback GROUP BY status",
    );
    return {
      items: rows.map(({ total: _t, ...r }) => r),
      total: rows[0]?.total ?? 0,
      page: q.page,
      limit: q.limit,
      statusCounts: Object.fromEntries(
        FEEDBACK_STATUSES.map((s) => [s, counts.find((c) => c.status === s)?.n ?? 0]),
      ) as Record<FeedbackStatus, number>,
    };
  }

  async get(id: string) {
    const row = await this.db.one(
      `SELECT ${ADMIN_COLUMNS} FROM customer_feedback f LEFT JOIN staff s ON s.id = f.moderated_by WHERE f.id = $1`,
      [id],
    );
    if (!row) throw new NotFoundException("Feedback not found.");
    return row;
  }

  /** Applies one moderation action atomically (the status is checked in the same UPDATE). */
  async moderate(id: string, action: Action, note: string | undefined, staff: AuthStaff) {
    const t = TRANSITIONS[action];
    const cleanNote = cleanLine(note);
    const row = await this.db.one<{ id: string }>(
      `UPDATE customer_feedback
          SET status = $2, moderated_at = now(), moderated_by = $3,
              moderation_note = coalesce($4, moderation_note),
              approved_at = CASE WHEN $2 = 'approved' THEN coalesce(approved_at, now()) ELSE approved_at END
        WHERE id = $1 AND status = ANY($5::text[]) RETURNING id`,
      [id, t.to, staff.id, cleanNote, t.from],
    );
    if (!row) {
      const current = await this.db.one<{ status: FeedbackStatus }>(
        "SELECT status FROM customer_feedback WHERE id = $1",
        [id],
      );
      if (!current) throw new NotFoundException("Feedback not found.");
      throw new ConflictException(
        `This feedback is ${current.status}; it cannot be changed with "${action}".`,
      );
    }
    await this.audit.log(staff.id, `feedback.${action}`, "customer_feedback", id, {
      status: t.to,
      ...(cleanNote ? { note: true } : {}),
    });
    return this.get(id);
  }
}

/**
 * Public, no login:
 *   POST /api/v1/feedback — JSON (see FeedbackInput). Always starts "pending".
 *   GET  /api/v1/feedback — approved feedback only.
 */
@Controller("feedback")
export class PublicFeedbackController {
  constructor(private readonly feedback: FeedbackService) {}

  @Post()
  @HttpCode(201)
  @Throttle({ default: { limit: 4, ttl: 10 * 60_000 } })
  submit(@Body() body: FeedbackInput) {
    return this.feedback.submit(body);
  }

  @Get()
  async list(@Query() q: PublicFeedbackQuery, @Res({ passthrough: true }) res: Response) {
    // Short cache: a hidden review disappears from the website within a minute.
    res.setHeader("Cache-Control", "public, max-age=60");
    return this.feedback.listPublic(q.limit);
  }
}

@Controller("admin/feedback")
@UseGuards(StaffAuthGuard)
@RequirePermission("feedback:moderate")
export class AdminFeedbackController {
  constructor(private readonly feedback: FeedbackService) {}

  @Get()
  list(@Query() q: AdminFeedbackQuery) {
    return this.feedback.list(q);
  }

  @Get(":id")
  get(@Param("id", ParseUUIDPipe) id: string) {
    return this.feedback.get(id);
  }

  @Post(":id/approve")
  @HttpCode(200)
  approve(@Param("id", ParseUUIDPipe) id: string, @Body() b: ModerationBody, @CurrentStaff() s: AuthStaff) {
    return this.feedback.moderate(id, "approve", b.note, s);
  }

  @Post(":id/reject")
  @HttpCode(200)
  reject(@Param("id", ParseUUIDPipe) id: string, @Body() b: ModerationBody, @CurrentStaff() s: AuthStaff) {
    return this.feedback.moderate(id, "reject", b.note, s);
  }

  @Post(":id/hide")
  @HttpCode(200)
  hide(@Param("id", ParseUUIDPipe) id: string, @Body() b: ModerationBody, @CurrentStaff() s: AuthStaff) {
    return this.feedback.moderate(id, "hide", b.note, s);
  }

  /** Republishing hidden feedback is admin-only (like restoring an archived delivery area). */
  @Post(":id/restore")
  @HttpCode(200)
  @RequirePermission("feedback:restore")
  restore(@Param("id", ParseUUIDPipe) id: string, @Body() b: ModerationBody, @CurrentStaff() s: AuthStaff) {
    return this.feedback.moderate(id, "restore", b.note, s);
  }
}

@Module({
  controllers: [PublicFeedbackController, AdminFeedbackController],
  providers: [FeedbackService],
})
export class FeedbackModule {}
